package booktest

import os.Path

import scala.collection.mutable
import scala.util.Try

/**
 * Where cache entries live, and why they live there.
 *
 * An entry is only useful if the machine running the gate can SEE it, so for a
 * hosted CI the entries have to travel with the change — i.e. be committed. That
 * makes the storage layout a real design constraint, not a detail:
 *
 * ONE FILE PER CASE DOES NOT WORK AT SCALE. A consumer with ~2,400 cases would
 * get ~2,400 FILES, and because the shared half of the key covers the main
 * code, every commit that touches it invalidates all of them at once. A
 * four-file pull request would arrive as a 2,400-file diff, and any two
 * concurrent PRs would conflict in all of them. That is unusable, and it gets
 * worse as the suite grows.
 *
 * So the manifest is FACTORED into the part that is shared and the part that is
 * per-case:
 *
 *   keyVersion=1
 *   classpath=<sha>          # shared: main code + dependency jars
 *   env=<sha>                # shared: locale, timezone, -p
 *   <suite>/<case> <sha>     # per-case: its snapshots + the test code its
 *                            #           suite reaches
 *
 * Now a main-code change rewrites ONE LINE — `classpath=` — and the diff says
 * exactly what happened: the code moved, so everything must re-run. Editing one
 * test rewrites only that suite's lines. Conflicts are confined to a single
 * file that can be regenerated by re-running, and a reviewer can read it.
 *
 * The key for a case is still the hash of all of it, so nothing about the
 * soundness argument changes: a case matches only if the shared digests AND its
 * own per-case digest are the ones recorded.
 */
class CacheManifest(file: Path, digests: Fingerprint.Digests) {

  private val lock = new Object
  /** case-key -> per-case digest, as recorded on disk (or written this run) */
  private val entries = mutable.LinkedHashMap[String, String]()
  private var loadedClasspath: Option[String] = None
  private var loadedEnv: Option[String] = None
  private var loadedKeyVersion: Option[String] = None
  private var dirty = false

  load()

  private def load(): Unit = Try {
    if (os.exists(file)) os.read.lines(file).foreach { raw =>
      val line = raw.trim
      if (line.nonEmpty && !line.startsWith("#")) {
        if (line.startsWith("keyVersion=")) loadedKeyVersion = Some(line.stripPrefix("keyVersion="))
        else if (line.startsWith("classpath=")) loadedClasspath = Some(line.stripPrefix("classpath="))
        else if (line.startsWith("env=")) loadedEnv = Some(line.stripPrefix("env="))
        else line.split("\\s+", 2) match {
          case Array(name, snap) => entries(name) = snap
          case _ => ()  // unparseable line: ignored, which means "no entry", which means "run it"
        }
      }
    }
  }.getOrElse(())

  /** True only if the shared digests recorded on disk are the ones we computed
    * for THIS run. If the code, locale, timezone or -p moved, nothing in the
    * manifest applies and every case must run. */
  private def sharedMatch: Boolean =
    loadedKeyVersion.contains(Fingerprint.KeyVersion) &&
      loadedClasspath.contains(digests.classpath) &&
      loadedEnv.contains(digests.environment)

  /** Does this case have a valid cache entry? Absent manifest, stale shared digest,
    * missing entry, or a different per-case digest all answer false — i.e.
    * "run the test". There is no path here that answers true on doubt. */
  def matches(fullName: String, caseDigest: String): Boolean = lock.synchronized {
    sharedMatch && entries.get(fullName).contains(caseDigest)
  }

  /** Record a pass. Held in memory and written once, at the end of the run:
    * rewriting a 2,400-line file after every case would cost more than it saves,
    * and a partial file written mid-run is a file that lies if the run dies. */
  def record(fullName: String, caseDigest: String): Unit = lock.synchronized {
    if (!sharedMatch) {
      // The shared digests moved, so every remembered entry describes a
      // different world. Drop them rather than carry a mixed manifest — a
      // half-valid manifest is exactly the kind of thing that produces a stale
      // pass later.
      entries.clear()
      loadedKeyVersion = Some(Fingerprint.KeyVersion)
      loadedClasspath = Some(digests.classpath)
      loadedEnv = Some(digests.environment)
    }
    entries(fullName) = caseDigest
    dirty = true
  }

  /** Forget a case (used when the verifier proves an entry lied). */
  def invalidate(fullName: String): Unit = lock.synchronized {
    if (entries.remove(fullName).isDefined) dirty = true
  }

  def isEmpty: Boolean = lock.synchronized { entries.isEmpty }

  /** Write the manifest, sorted, so the file is stable and its diffs are
    * meaningful rather than reordered noise. */
  def flush(): Unit = lock.synchronized {
    if (!dirty) return
    Try {
      os.makeDir.all(file / os.up)
      val body = Seq(
        "# booktest cache entries — cases that PASSED for the inputs recorded here.",
        "# A cache, not an authority: if anything below does not match, the test runs.",
        "#",
        "# classpath/env are shared by every case, so a main-code change rewrites ONE line",
        "# and every case is invalidated at once. A per-case entry covers that case's",
        "# accepted snapshots plus the test code its suite reaches.",
        s"keyVersion=${Fingerprint.KeyVersion}",
        s"classpath=${digests.classpath}",
        s"env=${digests.environment}") ++
        entries.toSeq.sortBy(_._1).map { case (n, s) => s"$n $s" }
      os.write.over(file, body.mkString("\n") + "\n")
      dirty = false
    }.getOrElse(())
  }
}
